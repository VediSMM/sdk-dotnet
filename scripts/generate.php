function apiReference(array $services, array $grouped, array $headings, bool $russian): string
{
    $lines = [
        $russian ? '# Справочник API .NET SDK' : '# .NET SDK API reference',
        '',
        $russian
            ? 'Все 83 пользовательские операции доступны как асинхронные методы с `Task<ApiResponse>`. Передавайте `CallOptions` и `CancellationToken`; административных методов в SDK нет.'
            : 'All 83 user operations are exposed as asynchronous `Task<ApiResponse>` methods. Pass `CallOptions` and a `CancellationToken`; administrative methods are intentionally absent.',
        '',
    ];
    foreach ($services as $tag => [$property]) {
        $lines[] = '## ' . ($headings[$tag] ?? $tag);
        $lines[] = '';
        $lines[] = $russian
            ? '| Метод SDK | HTTP | Путь | Права |'
            : '| SDK method | HTTP | Path | Scopes |';
        $lines[] = '| --- | --- | --- | --- |';
        foreach ($grouped[$tag] as $operation) {
            $scopes = $operation['scopes'] ?? [];
            $lines[] = sprintf(
                '| `sdk.%s.%sAsync(options, cancellationToken)` | `%s` | `%s` | %s |',
                $property,
                pascal((string) $operation['operation_id']),
                strtoupper((string) $operation['method']),
                (string) $operation['path'],
                $scopes === [] ? '—' : implode(', ', array_map(static fn ($scope): string => '`' . $scope . '`', $scopes)),
            );
        }
        $lines[] = '';
    }
    return rtrim(implode("\n", $lines)) . "\n";
}

