function csString(string $value): string
{
    return json_encode($value, JSON_THROW_ON_ERROR | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
}

function csList(array $values): string
{
    if ($values === []) {
        return 'R()';
    }
    return 'R(' . implode(', ', array_map(static fn ($value): string => csString((string) $value), $values)) . ')';
}

function pascal(string $operationId): string
{
    return strtoupper($operationId[0]) . substr($operationId, 1);
}

