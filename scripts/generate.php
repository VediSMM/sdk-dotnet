function apiReference(array $services, array $grouped, array $headings, bool $russian): string
{
    $focused = [
        'archiveTrackingLink' => ['ArchiveAsync', 'id, options, cancellationToken'],
        'createTrackingLink' => ['CreateAsync', 'request, options, cancellationToken'],
        'disableTrackingLink' => ['DisableAsync', 'id, options, cancellationToken'],
        'getTrackingLink' => ['GetAsync', 'id, options, cancellationToken'],
        'listTrackingLinks' => ['ListAsync', 'query, options, cancellationToken'],
        'getTrackingAnalyticsGeo' => ['GeoAsync', 'filter, options, cancellationToken'],
        'getTrackingAnalyticsSummary' => ['SummaryAsync', 'filter, options, cancellationToken'],
        'getTrackingAnalyticsTimeseries' => ['TimeseriesAsync', 'filter, options, cancellationToken'],
        'listTrackingAnalyticsLinks' => ['LinksAsync', 'filter, options, cancellationToken'],
        'listTrackingAnalyticsPosts' => ['PostsAsync', 'filter, options, cancellationToken'],
        'listTrackingAnalyticsSources' => ['SourcesAsync', 'filter, options, cancellationToken'],
    ];
    $lines = [
        $russian ? '# Справочник API .NET SDK' : '# .NET SDK API reference',
        '',
        $russian
            ? 'Все 94 пользовательские операции доступны как асинхронные методы с `Task<ApiResponse>`. Передавайте `CallOptions` и `CancellationToken`; административных методов в SDK нет.'
            : 'All 94 user operations are exposed as asynchronous `Task<ApiResponse>` methods. Pass `CallOptions` and a `CancellationToken`; administrative methods are intentionally absent.',
        '',
    ];
    foreach ($services as $tag => [$property]) {
        $lines[] = '## ' . ($headings[$tag] ?? $tag);
        $lines[] = '';
        $lines[] = $russian
            ? '| Метод SDK | HTTP | Путь | Права |'
            : '| SDK method | HTTP | Path | Scopes |';
        $lines[] = '| --- | --- | --- | --- |';
        foreach ($grouped[$tag] as $operation) {
            $scopes = $operation['scopes'] ?? [];
            $id = (string) $operation['operation_id'];
            [$method, $arguments] = $focused[$id] ?? [pascal($id) . 'Async', 'options, cancellationToken'];
            $lines[] = sprintf(
                '| `sdk.%s.%s(%s)` | `%s` | `%s` | %s |',
                $property,
                $method,
                $arguments,
                strtoupper((string) $operation['method']),
                (string) $operation['path'],
                $scopes === [] ? '—' : implode(', ', array_map(static fn ($scope): string => '`' . $scope . '`', $scopes)),
            );
        }
        $lines[] = '';
    }
    return rtrim(implode("\n", $lines)) . "\n";
}

